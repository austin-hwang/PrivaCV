function Button({
  className,
  variant = "default",
  size = "default",
  unstyled = false,
  title,
  ref: forwardedRef,
  ...props
}: Omit<ButtonPrimitiveProps, "className"> &
  React.RefAttributes<HTMLButtonElement> &
  VariantProps<typeof buttonVariants> & {
    className?: string;
    // React Aria filters `title` off the DOM node, so set it via a ref effect to
    // keep hover tooltips (and title-based queries) working on icon buttons.
    title?: string;
    // Skip the variant/size base styling for bespoke controls (calendar cells,
    // color swatches, toolbar toggles) that supply their own className but still
    // want to route through this shadcn wrapper.
    unstyled?: boolean;
  }) {
  const innerRef = React.useRef<HTMLButtonElement>(null);
  React.useEffect(() => {
    const node = innerRef.current;
    if (!node) return;
    if (title != null) node.setAttribute("title", title);
    else node.removeAttribute("title");
  }, [title]);
  const setRef = React.useCallback(
    (node: HTMLButtonElement | null) => {
      innerRef.current = node;
      if (typeof forwardedRef === "function") forwardedRef(node);
      else if (forwardedRef) forwardedRef.current = node;
    },
    [forwardedRef],
  );
  return (
    <ButtonPrimitive
      ref={setRef}
      data-slot="button"
      data-variant={unstyled ? undefined : variant}
      data-size={unstyled ? undefined : size}
      className={unstyled ? cn(className) : cn(buttonVariants({ variant, size, className }))}
      {...props}
    />
  );
}

function LinkButton({
  className,
  variant = "default",
  size = "default",
  ...props
}: Omit<LinkPrimitiveProps, "className"> &
  VariantProps<typeof buttonVariants> & {
    className?: string;
  }) {
  return (
    <LinkPrimitive
      data-slot="button"
      data-variant={variant}
      data-size={size}
      className={cn(buttonVariants({ variant, size, className }))}
      {...props}
    />
  );
}

